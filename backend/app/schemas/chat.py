"""Pydantic schemas for Groq-powered Retrieval-Augmented Generation (RAG) chat."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator

from backend.app.utils.helpers import validate_document_id


class ChatRequest(BaseModel):
    """Payload for asking questions about indexed documents using RAG."""

    question: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Natural language question to ask about the uploaded documents",
    )
    document_ids: Optional[List[str]] = Field(
        default=None,
        description="Optional list of document IDs to restrict retrieval scope",
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Maximum number of context chunks to retrieve from FAISS (1-20)",
    )
    score_threshold: Optional[float] = Field(
        default=0.20,
        ge=-1.0,
        le=1.0,
        description="Minimum cosine similarity score threshold for context inclusion (-1.0 to 1.0)",
    )
    temperature: Optional[float] = Field(
        default=0.2,
        ge=0.0,
        le=1.0,
        description="LLM generation temperature (lower values ensure grounded, factual answers)",
    )
    max_tokens: Optional[int] = Field(
        default=1024,
        ge=64,
        le=4096,
        description="Maximum tokens to generate in the answer (64-4096)",
    )

    @field_validator("document_ids")
    @classmethod
    def validate_document_ids_list(cls, v: Optional[List[str]]) -> Optional[List[str]]:
        """Ensure document_ids list is within safe size and each ID is valid."""
        if v is None:
            return v
        if len(v) > 50:
            raise ValueError("document_ids list cannot exceed 50 items")
        for doc_id in v:
            if not validate_document_id(doc_id):
                raise ValueError(f"Invalid document ID format in document_ids: '{doc_id}'")
        return v


class ChatSource(BaseModel):
    """Source reference representing a factual context chunk retrieved from FAISS."""

    chunk_id: str = Field(..., description="Unique chunk identifier")
    document_id: str = Field(..., description="Source document identifier")
    filename: str = Field(..., description="Original filename of the source document")
    chunk_index: int = Field(..., description="Sequence position of the chunk in the document")
    page_number: Optional[int] = Field(
        default=None,
        description="1-indexed page number if retrieved from a PDF",
    )
    section_index: Optional[int] = Field(
        default=None,
        description="1-indexed section or paragraph index if retrieved from DOCX/TXT",
    )
    heading: Optional[str] = Field(
        default=None,
        description="Section heading or title if available",
    )
    text: str = Field(..., description="Excerpt text content from the document chunk")
    score: float = Field(..., description="Cosine similarity score of this chunk to the query")


class ChatResponse(BaseModel):
    """Structured response payload for RAG question answering."""

    answer: str = Field(..., description="Grounded answer generated by the LLM from document context")
    question: str = Field(..., description="Original question submitted by user")
    sources: List[ChatSource] = Field(
        default_factory=list,
        description="Exact document chunks retrieved and supplied as evidence context to the LLM",
    )
    model: str = Field(..., description="Groq model ID used to generate the answer")
    evidence_found: bool = Field(
        ...,
        description="Indicates whether relevant document evidence was found for the question",
    )
    total_sources: int = Field(..., description="Total count of retrieved source citations")
    usage: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Token consumption telemetry from Groq API (prompt_tokens, completion_tokens, total_tokens)",
    )


class ChatStatusResponse(BaseModel):
    """Operational diagnostics of the Groq RAG service."""

    ready: bool = Field(..., description="Whether Groq service is initialized and configured")
    model: str = Field(..., description="Configured Groq model identifier")
    groq_configured: bool = Field(..., description="Whether a valid GROQ_API_KEY is present")
    max_context_chars: int = Field(..., description="Maximum character ceiling for retrieved context injection")
    default_top_k: int = Field(..., description="Default top_k chunks retrieved per question")
